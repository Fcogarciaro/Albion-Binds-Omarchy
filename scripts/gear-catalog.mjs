// Pure transform from the ao-bin-dumps items list to the Zona negra gear
// catalog. The build script (build-gear-catalog.mjs) does the I/O.

const GEAR_SLOTS = { HEAD: "head", ARMOR: "armor", SHOES: "shoes", MAIN: "mainhand", "2H": "mainhand", OFF: "offhand", MOUNT: "mount" }
const CONSUMABLE_SLOTS = { POTION: "potion", MEAL: "food" }

// Spanish tier grade appended to gear names ("Casco de soldado del maestro").
const TIER_ADJECTIVES = {
  1: "principiante", 2: "novato", 3: "obrero", 4: "iniciado",
  5: "experto", 6: "maestro", 7: "gran maestro", 8: "anciano"
}

const EXCLUDED = /(_SKIN|SKIN_|_BP$|PROTOTYPE|_TEST|MOUNTUPGRADE|ARTEFACT|SPECIAL_FOOD|_XMAS|SIEGE)/

export function tierOf(uniqueName) {
  const m = /^T(\d)_/.exec(uniqueName)
  return m ? Number(m[1]) : null
}

export function baseOf(uniqueName) {
  return uniqueName.replace(/^T\d_/, "").replace(/@\d$/, "")
}

// Slot id for an equippable or consumable item, or null for anything else
// (resources, journals, artifacts, skins, decorative capes, unique/event items).
export function slotOf(uniqueName) {
  if (tierOf(uniqueName) === null || EXCLUDED.test(uniqueName)) return null
  const base = baseOf(uniqueName)
  if (base === "CAPE" || base.startsWith("CAPEITEM_")) return "cape"
  if (base === "BAG" || base === "BAG_INSIGHT") return "bag"
  const prefix = base.split("_")[0]
  if (CONSUMABLE_SLOTS[prefix]) return CONSUMABLE_SLOTS[prefix]
  if (prefix === "MOUNT" && base !== "MOUNT") return "mount"
  return GEAR_SLOTS[prefix] || null
}

// Removes the tier grade ("del maestro") when it matches that tier; otherwise
// the name is returned unchanged.
export function stripTierAdjective(name, tier) {
  const adjective = TIER_ADJECTIVES[tier]
  if (!adjective) return name
  const re = new RegExp("\\s+del?\\s+" + adjective + "$", "i")
  return re.test(name) ? name.replace(re, "") : name
}

const POTION_GRADE = /\s+(menor|mayor)$/i

function spanishName(entry) {
  const names = entry.LocalizedNames
  if (!names || typeof names !== "object") return null
  return names["ES-ES"] || names["EN-US"] || null
}

// items: parsed formatted/items.json. Returns [{ base, slot, nameEs, tiers }]
// sorted by base, tiers ascending, enchant variants collapsed.
export function buildCatalog(items) {
  const bases = new Map()
  for (const entry of items) {
    const id = entry && entry.UniqueName
    if (typeof id !== "string") continue
    const slot = slotOf(id)
    const name = slot && spanishName(entry)
    if (!name) continue
    const base = baseOf(id)
    const tier = tierOf(id)
    if (!bases.has(base)) bases.set(base, { slot, names: new Map() })
    const group = bases.get(base)
    if (!group.names.has(tier)) group.names.set(tier, name)
  }
  const catalog = []
  for (const [base, { slot, names }] of bases) {
    const tiers = [...names.keys()].sort((a, b) => a - b)
    // Every tier keeps its official full name so it can be searched
    // ("Bolsa del iniciado"); nameEs is the generic base name.
    const perTier = {}
    for (const t of tiers) perTier[t] = names.get(t)
    const first = names.get(tiers[0])
    const nameEs = slot === "potion" || slot === "food" ? first.replace(POTION_GRADE, "") : stripTierAdjective(first, tiers[0])
    catalog.push({ base, slot, nameEs, tiers, names: perTier })
  }
  return catalog.sort((a, b) => (a.base < b.base ? -1 : a.base > b.base ? 1 : 0))
}

export function renderCatalogModule(catalog) {
  const rows = catalog.map((e) => "  " + JSON.stringify(e)).join(",\n")
  return "// Generated by scripts/build-gear-catalog.mjs from ao-data/ao-bin-dumps. Do not edit.\n"
    + ".pragma library\n\nvar ITEMS = [\n" + rows + "\n]\n"
}
